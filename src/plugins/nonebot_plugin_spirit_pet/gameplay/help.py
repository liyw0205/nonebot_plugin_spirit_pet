def help_link(line: str) -> tuple[str, str] | None:
    for section, entries in _HELP_SECTIONS.items():
        if line == f"灵宠帮助 {section}：{_OVERVIEW[section]}":
            return section, f"灵宠帮助 {section}"
        for label, command, description in entries:
            if line == f"{label}：{description}":
                return label, command
    if line == "灵宠帮助：再看看其他玩法。":
        return "帮助总览", "灵宠帮助"
    return None


def help_game(ctx, arg: str) -> Reply:
    section = arg.strip()
    if section:
        entries = _HELP_SECTIONS.get(section)
        if entries is None:
            raise GameError("这卷游记还未收录，先看看灵宠帮助吧。")
        return Reply(f"帮助 · {section}", (
            *(f"{label}：{description}" for label, _, description in entries),
            "", "灵宠帮助：再看看其他玩法。",
        ), ())
    return Reply("灵宠仙途", (
        "与山海灵宠结契，一起修行、探险，留下属于你们的故事。",
        "", *(f"灵宠帮助 {name}：{description}" for name, description in _OVERVIEW.items()),
    ), ())
